"""One registered tool: its schema, its callable, and what it declares about itself."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Callable, Optional

from aisuite.utils.tools import Tools

from ..contract import ToolContract


@dataclass
class ToolSpec:
    name: str
    schema: dict[str, Any]  # an OpenAI-format function tool schema
    func: Callable[..., Any]
    metadata: Any = None  # aisuite ToolMetadata, or None
    # What the tool declares about its output (see contract.py). None for a tool that has not
    # migrated, and the runtime then renders it as it always did.
    contract: Optional[ToolContract] = None
    # Where the tool came from, when that source can change while a session is open (see
    # `sync_group`). None for the built-ins, which are fixed for the engine's life.
    group: Optional[str] = None
    # Whether this tool may leave the wire under progressive discovery. A deferrable tool
    # is still callable, through the `tool_call` bridge or from inside a program, but its schema is
    # not published while the mode is on. MCP and connector tools declare it; the situational
    # built-ins are deferred by name (`mark_deferred`). Interactive tools never are, since deferring
    # one was seen to collapse how much it is used.
    defer: bool = False
    # The heading the deferred index lists the tool under (`catalog_index`): a connector's name. An
    # MCP tool's server is read from its name, and None is `built-in`.
    catalog: Optional[str] = None
    # An argument-conditional policy: a callable(arguments) -> metadata that the engine consults per
    # call, in place of the static `metadata`, which then serves only the readers that go by name
    # (pipeline listeners, risk classification). It is for a tool whose arguments change its own risk
    # profile. One spawning tool has several postures: read-only types are parallel-safe, and the
    # write type is gated and serial.
    policy: Optional[Callable[[dict[str, Any]], Any]] = None
    # A schema that describes the registry and not one fixed function. Today only `tool_search`, whose
    # description lists the deferred catalog (2026-09-24). It is called wherever
    # the wire schema is read, so an MCP server armed mid-session shows up on the next request, and
    # the bytes change only when the catalog does, since the tool list is part of the cached prefix.
    live_schema: Optional[Callable[[], dict[str, Any]]] = None
    # The closure holds one session's state (its goal, wakes, schedule origin, channel subscriptions,
    # history, team seat) and never crosses into another session's registry:
    # `filtered(session_bound=False)` leaves it behind.
    session_bound: bool = False

    def wire_schema(self) -> dict[str, Any]:
        """The schema a request carries for this tool. A live schema that raises falls back to the
        static one, because a description must never cost a turn."""
        if self.live_schema is not None:
            try:
                live = self.live_schema()
                if isinstance(live, dict):
                    return live
            except Exception:  # noqa: BLE001 - the static schema is always correct
                pass
        return self.schema


def schema_for(func: Callable[..., Any]) -> dict[str, Any]:
    """One OpenAI-format tool schema, generated by aisuite."""
    return Tools([func]).tools(format="openai")[0]
